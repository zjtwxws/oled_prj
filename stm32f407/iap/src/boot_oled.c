/**
 * @file    boot_oled.c
 * @brief   Bootloader OLED 显示 — 位控 I2C + SSD1306 驱动 + 精简字库 + 进度显示
 *
 * 不依赖 HAL I2C 模块，使用 GPIO 位控 PB10(SCL)/PB11(SDA) 模拟 I2C 时序。
 * 字库仅包含 ASCII 8×16 (95 字符) + 19 个升级状态所需汉字。
 */

#include "boot_oled.h"
#include "main.h"
#include "stm32f4xx_hal.h"
#include <string.h>

/* ================================================================
 *  位控 I2C (PB10=SCL, PB11=SDA, 开漏+上拉)
 * ================================================================ */

#define I2C_PORT    GPIOB
#define I2C_SCL     GPIO_PIN_10
#define I2C_SDA     GPIO_PIN_11

static void delay_5us(void)
{
    for (volatile uint32_t i = 0; i < 210; i++)
    {
        __NOP();
    }
}

static void i2c_scl_h(void) { HAL_GPIO_WritePin(I2C_PORT, I2C_SCL, GPIO_PIN_SET); }
static void i2c_scl_l(void) { HAL_GPIO_WritePin(I2C_PORT, I2C_SCL, GPIO_PIN_RESET); }
static void i2c_sda_h(void) { HAL_GPIO_WritePin(I2C_PORT, I2C_SDA, GPIO_PIN_SET); }
static void i2c_sda_l(void) { HAL_GPIO_WritePin(I2C_PORT, I2C_SDA, GPIO_PIN_RESET); }
static uint8_t i2c_sda_read(void) { return (HAL_GPIO_ReadPin(I2C_PORT, I2C_SDA) == GPIO_PIN_SET) ? 1 : 0; }

static void i2c_start(void)
{
    i2c_sda_h();
    i2c_scl_h();
    delay_5us();
    i2c_sda_l();
    delay_5us();
    i2c_scl_l();
}

static void i2c_stop(void)
{
    i2c_sda_l();
    i2c_scl_h();
    delay_5us();
    i2c_sda_h();
    delay_5us();
}

static int i2c_write_byte(uint8_t data)
{
    for (uint8_t i = 0; i < 8; i++)
    {
        if (data & 0x80)
        {
            i2c_sda_h();
        }
        else
        {
            i2c_sda_l();
        }
        delay_5us();
        i2c_scl_h();
        delay_5us();
        i2c_scl_l();
        data <<= 1;
    }

    i2c_sda_h();
    delay_5us();
    i2c_scl_h();
    delay_5us();
    uint8_t ack = i2c_sda_read();
    i2c_scl_l();
    delay_5us();
    return (ack == 0) ? 0 : -1;
}

static void oled_write_cmd(uint8_t cmd)
{
    i2c_start();
    i2c_write_byte(0x78);
    i2c_write_byte(0x00);
    i2c_write_byte(cmd);
    i2c_stop();
}

static void oled_write_data(uint8_t data)
{
    i2c_start();
    i2c_write_byte(0x78);
    i2c_write_byte(0x40);
    i2c_write_byte(data);
    i2c_stop();
}

/* ================================================================
 *  SSD1306 初始化和基础操作
 * ================================================================ */

static uint8_t oled_buf[OLED_WIDTH * OLED_PAGES];

static const uint8_t ssd1306_init_cmds[] =
{
    0xAE, 0x20, 0x00, 0x40, 0xA0, 0xC0,
    0xA8, 0x3F, 0xD3, 0x00, 0xD5, 0xF0,
    0xD9, 0x22, 0xDA, 0x12, 0xDB, 0x20,
    0x81, 0xFF, 0xA4, 0xA6, 0x8D, 0x14,
    0x2E, 0xAF
};

/**
 * @brief  初始化 SSD1306 OLED
 */
void boot_oled_init(void)
{
    for (volatile uint32_t i = 0; i < 8400000; i++)
    {
        __NOP();
    }

    for (uint16_t i = 0; i < sizeof(ssd1306_init_cmds); i++)
    {
        oled_write_cmd(ssd1306_init_cmds[i]);
    }

    boot_oled_clear();
    boot_oled_flush();
}

/**
 * @brief  清空显存缓冲区
 */
void boot_oled_clear(void)
{
    memset(oled_buf, 0x00, sizeof(oled_buf));
}

/**
 * @brief  设置光标位置
 */
void boot_oled_set_cursor(uint8_t page, uint8_t col)
{
    oled_write_cmd(0xB0 + (page & 0x07));
    oled_write_cmd(0x00 + (col & 0x0F));
    oled_write_cmd(0x10 + ((col >> 4) & 0x0F));
}

/**
 * @brief  刷新显存到 OLED
 */
void boot_oled_flush(void)
{
    for (uint8_t page = 0; page < OLED_PAGES; page++)
    {
        boot_oled_set_cursor(page, 0);
        i2c_start();
        i2c_write_byte(0x78);
        i2c_write_byte(0x40);
        for (uint8_t col = 0; col < OLED_WIDTH; col++)
        {
            i2c_write_byte(oled_buf[page * OLED_WIDTH + col]);
        }
        i2c_stop();
    }
}

/**
 * @brief  绘制单个像素到缓冲区
 */
static void oled_set_pixel(uint8_t x, uint8_t y, uint8_t on)
{
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT)
    {
        return;
    }

    uint8_t page = y / 8;
    uint8_t bit  = y & 7;

    if (on)
    {
        oled_buf[page * OLED_WIDTH + x] |= (1 << bit);
    }
    else
    {
        oled_buf[page * OLED_WIDTH + x] &= ~(1 << bit);
    }
}

