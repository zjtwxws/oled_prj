/* ================================================================
 *  文本渲染
 * ================================================================ */

#define FONT_ASCII_W    8
#define FONT_ASCII_H    16
#define FONT_CHINESE_W  16

/**
 * @brief  查找汉字字模 (UTF-8 3字节比对)
 */
static const uint8_t* cn_font_lookup(const char *utf8)
{
    for (size_t i = 0; i < CN_FONT_COUNT; i++)
    {
        const char *tbl = cn_font_table[i].utf8;
        if (tbl[0] == utf8[0] && tbl[1] == utf8[1] && tbl[2] == utf8[2])
        {
            return cn_font_table[i].glyph;
        }
    }
    return NULL;
}

/**
 * @brief  绘制 ASCII 字符到缓冲区 (8×16)
 */
static uint8_t draw_ascii(uint8_t x, uint8_t page, char ch)
{
    if (x + FONT_ASCII_W > OLED_WIDTH || page >= OLED_PAGES - 1)
    {
        return x;
    }

    if (ch < 0x20 || ch > 0x7E)
    {
        ch = ' ';
    }

    const uint8_t *glyph = &ascii_8x16[ch - 0x20][0];
    for (uint8_t col = 0; col < FONT_ASCII_W; col++)
    {
        oled_buf[page * OLED_WIDTH + x + col] = glyph[col];
        oled_buf[(page + 1) * OLED_WIDTH + x + col] = glyph[col + 8];
    }
    return x + FONT_ASCII_W;
}

/**
 * @brief  绘制汉字到缓冲区 (16×16)
 */
static uint8_t draw_chinese(uint8_t x, uint8_t page, const char *utf8)
{
    if (x + FONT_CHINESE_W > OLED_WIDTH || page >= OLED_PAGES - 1)
    {
        return x;
    }

    const uint8_t *glyph = cn_font_lookup(utf8);
    if (glyph == NULL)
    {
        return x + FONT_CHINESE_W;
    }

    for (uint8_t col = 0; col < FONT_CHINESE_W; col++)
    {
        oled_buf[page * OLED_WIDTH + x + col] = glyph[col];
        oled_buf[(page + 1) * OLED_WIDTH + x + col] = glyph[col + 16];
    }
    return x + FONT_CHINESE_W;
}

/**
 * @brief  计算混合文本像素宽度
 */
static uint8_t text_width(const char *text)
{
    const char *p = text;
    uint8_t w = 0;
    while (*p)
    {
        uint8_t first = (uint8_t)*p;
        if ((first & 0x80) && (first & 0xF0) == 0xE0)
        {
            w += FONT_CHINESE_W;
            p += 3;
        }
        else if ((first & 0x80) && (first & 0xE0) == 0xC0)
        {
            p += 2;
        }
        else
        {
            w += FONT_ASCII_W;
            p++;
        }
    }
    return w;
}

/**
 * @brief  在指定位置绘制混合文本 (ASCII + 中文)
 */
static void draw_text_at(uint8_t page, uint8_t x, const char *text)
{
    const char *p = text;
    while (*p && x < OLED_WIDTH)
    {
        uint8_t first = (uint8_t)*p;
        if ((first & 0x80) && (first & 0xF0) == 0xE0)
        {
            if (x + FONT_CHINESE_W > OLED_WIDTH)
            {
                break;
            }
            x = draw_chinese(x, page, p);
            p += 3;
        }
        else if ((first & 0x80) && (first & 0xE0) == 0xC0)
        {
            p += 2;
        }
        else
        {
            x = draw_ascii(x, page, *p);
            p++;
        }
    }
}

/* ================================================================
 *  状态显示 API
 * ================================================================ */

/**
 * @brief  居中显示一行文本并立即刷新
 */
void boot_oled_status(const char *text)
{
    boot_oled_clear();
    uint8_t w = text_width(text);
    uint8_t x = (w >= OLED_WIDTH) ? 0 : ((OLED_WIDTH - w) / 2);
    draw_text_at(3, x, text);
    boot_oled_flush();
}

/**
 * @brief  显示进度条和百分比
 * @param  done   已下载字节
 * @param  total  总字节
 */
void boot_oled_progress(uint32_t done, uint32_t total)
{
    boot_oled_clear();

    uint8_t pct = (total > 0) ? (uint8_t)((done * 100UL) / total) : 0;

    /* 标题行 */
    draw_text_at(1, 0, "正在下载");

    /* 百分比 */
    char pct_str[8];
    int pos = 0;
    uint8_t tmp = pct;
    if (tmp >= 100) { pct_str[pos++] = '1'; tmp -= 100; }
    if (pct >= 10)  { pct_str[pos++] = (char)('0' + tmp / 10); }
    pct_str[pos++] = (char)('0' + tmp % 10);
    pct_str[pos++] = '%';
    pct_str[pos] = '\0';
    draw_text_at(3, 32, pct_str);

    /* 进度条 (page 5, x=8~119, 112 像素宽, 高度 16 像素 = page 4+5) */
    uint8_t bar_x = 8;
    uint8_t bar_w = 112;
    uint8_t fill  = (uint8_t)((done * (uint32_t)bar_w) / total);

    for (uint8_t col = bar_x; col < bar_x + bar_w; col++)
    {
        uint8_t is_fill = (col - bar_x < fill) ? 1 : 0;
        for (uint8_t bit = 0; bit < 8; bit++)
        {
            uint8_t y = 32 + bit;
            oled_set_pixel(col, y + 8, is_fill);
        }
    }

    boot_oled_flush();
}
